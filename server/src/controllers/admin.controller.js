const bcrypt = require('bcryptjs');
const mongoose = require('mongoose');
const User = require('../models/User');
const { sanitizeUser } = require('../utils/sanitizeUser');

const EMAIL_RE = /^\S+@\S+\.\S+$/;
const MIN_PASSWORD_LENGTH = 8;

/**
 * Validate the shared "create account" fields and return an error message or null.
 * (No password is required — it defaults to the account's email address.)
 */
const validateCommonFields = ({ name, email }) => {
  if (!name || !String(name).trim()) return 'Name is required.';
  if (!email || !String(email).trim()) return 'Email is required.';
  if (!EMAIL_RE.test(String(email).trim())) return 'Please provide a valid email address.';
  return null;
};

/**
 * Resolve the password for a newly created account.
 * No password is asked from the admin: it defaults to the account's email
 * address. (An explicit password is still honoured for API callers, with
 * the usual minimum length.) Hashed lowercased — auth is case-insensitive.
 */
const resolveAccountPassword = (password, normalizedEmail) => {
  if (password && String(password).trim()) {
    if (String(password).length < MIN_PASSWORD_LENGTH) {
      return { error: `Password must be at least ${MIN_PASSWORD_LENGTH} characters long.` };
    }
    return { password: String(password), isDefault: false };
  }
  return { password: normalizedEmail, isDefault: true };
};

/**
 * POST /api/admin/faculty  (Admin only)
 * Create a Faculty account (email must be unique, password is hashed).
 */
const createFaculty = async (req, res, next) => {
  try {
    const { name, email, password } = req.body || {};

    const error = validateCommonFields({ name, email });
    if (error) return res.status(400).json({ message: error });

    const normalizedEmail = String(email).trim().toLowerCase();

    const account = resolveAccountPassword(password, normalizedEmail);
    if (account.error) return res.status(400).json({ message: account.error });

    const existing = await User.findOne({ email: normalizedEmail });
    if (existing) {
      return res.status(409).json({ message: 'An account with this email already exists.' });
    }

    // Stored lowercased — login accepts the password in any capitalisation.
    const passwordHash = await bcrypt.hash(account.password.toLowerCase(), 10);
    const faculty = await User.create({
      name: String(name).trim(),
      email: normalizedEmail,
      passwordHash,
      role: 'faculty',
    });

    res.status(201).json({
      message: `Faculty account created for ${faculty.name}. ${
        account.isDefault ? 'Their password is their email address.' : 'An initial password was set for them.'
      }`,
      faculty: sanitizeUser(faculty),
    });
  } catch (err) {
    next(err);
  }
};

/**
 * GET /api/admin/faculty  (Admin only)
 * List all Faculty accounts (password hashes are never returned).
 */
const listFaculty = async (req, res, next) => {
  try {
    const faculty = await User.find({ role: 'faculty' }).select('-passwordHash').sort({ createdAt: -1 });
    res.json({ count: faculty.length, faculty: faculty.map(sanitizeUser) });
  } catch (err) {
    next(err);
  }
};

/**
 * POST /api/admin/students  (Admin only)
 * Create a Student account (email and roll number must be unique).
 * The unique, non-sensitive studentQrId is generated by the User model.
 */
const createStudent = async (req, res, next) => {
  try {
    const { name, email, password, rollNumber, branch } = req.body || {};

    const error = validateCommonFields({ name, email });
    if (error) return res.status(400).json({ message: error });
    if (!rollNumber || !String(rollNumber).trim()) {
      return res.status(400).json({ message: 'Roll number is required for students.' });
    }

    const normalizedEmail = String(email).trim().toLowerCase();
    const normalizedRoll = String(rollNumber).trim();

    const account = resolveAccountPassword(password, normalizedEmail);
    if (account.error) return res.status(400).json({ message: account.error });

    const existing = await User.findOne({
      $or: [{ email: normalizedEmail }, { rollNumber: normalizedRoll }],
    });
    if (existing) {
      const reason = existing.email === normalizedEmail ? 'email' : 'roll number';
      return res.status(409).json({ message: `An account with this ${reason} already exists.` });
    }

    // Stored lowercased — login accepts the password in any capitalisation.
    const passwordHash = await bcrypt.hash(account.password.toLowerCase(), 10);
    const student = await User.create({
      name: String(name).trim(),
      email: normalizedEmail,
      passwordHash,
      role: 'student',
      rollNumber: normalizedRoll,
      branch: branch ? String(branch).trim() : undefined,
    });

    res.status(201).json({
      message: `Student account created for ${student.name}. ${
        account.isDefault ? 'Their password is their email address.' : 'An initial password was set for them.'
      }`,
      student: sanitizeUser(student),
    });
  } catch (err) {
    next(err);
  }
};

/**
 * GET /api/admin/students  (Admin only)
 * List all Student accounts (password hashes are never returned).
 */
const listStudents = async (req, res, next) => {
  try {
    const students = await User.find({ role: 'student' }).select('-passwordHash').sort({ createdAt: -1 });
    res.json({ count: students.length, students: students.map(sanitizeUser) });
  } catch (err) {
    next(err);
  }
};

/**
 * PUT /api/admin/users/:userId/reset-password  (Admin only)
 * Reset a Faculty/Student account's password to that account's EMAIL
 * address — one click for the admin, and the new credential is easy to
 * communicate to the user. The admin's own password is fixed, so the
 * admin account can never be targeted here.
 */
const resetPassword = async (req, res, next) => {
  try {
    const { userId } = req.params;

    if (!mongoose.isValidObjectId(userId)) {
      return res.status(404).json({ message: 'Account not found.' });
    }

    const user = await User.findById(userId);
    if (!user) {
      return res.status(404).json({ message: 'Account not found.' });
    }
    if (user.role === 'admin') {
      return res.status(403).json({ message: 'The admin password cannot be reset.' });
    }

    // The new password IS the account's email address. For students the
    // roll-number part is presented in capitals (26951A1278@icare.ac.in) —
    // the way a roll number is written — while the hash stores the
    // lowercased form, so authentication stays case-insensitive either way.
    const newPassword =
      user.role === 'student' && user.email.includes('@')
        ? user.email.replace(/^[^@]+/, (local) => local.toUpperCase())
        : user.email;

    user.passwordHash = await bcrypt.hash(newPassword.toLowerCase(), 10);
    await user.save();

    res.json({ message: `Password reset for ${user.name}. Their new password is ${newPassword}.` });
  } catch (err) {
    next(err);
  }
};

module.exports = { createFaculty, listFaculty, createStudent, listStudents, resetPassword };
